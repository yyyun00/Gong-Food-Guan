def seed():
    init_db()
    with Session(engine) as s:
        added = updated = 0
        for name, emotion, price_tier in SEED_DATA:
            existing = s.exec(select(Restaurant).where(Restaurant.name == name)).first()
            if existing:
                existing.emotion_tags = emotion
                existing.price_tier   = price_tier
                s.add(existing)
                updated += 1
            else:
                s.add(Restaurant(
                    name=name,
                    category="手動整理",
                    price_tier=price_tier,
                    address="台北市公館商圈",
                    emotion_tags=emotion,
                ))
                added += 1
        s.commit()
        print(f"✅ 新增 {added} 筆，更新 {updated} 筆。")


if __name__ == "__main__":
    seed()